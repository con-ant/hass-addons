    @unittest.skipUnless(HAS_GIT, "git not installed")
    def test_git_guard_exclude_line_idempotent_and_tracked_warning(self):
        self.git("init", "-q")
        gitignore = self.s.ha_config / ".gitignore"
        self.assertFalse(gitignore.exists())

        out1, _ = self.render()
        out2, _ = self.render()
        exclude = self.s.ha_config / ".git" / "info" / "exclude"
        self.assertTrue(exclude.exists())
        lines = [l for l in exclude.read_text().splitlines() if l.strip() == "/claudecode_jobs.yaml"]
        self.assertEqual(len(lines), 1, exclude.read_text())
        self.assertFalse(gitignore.exists(), ".gitignore must never be created")
        self.assertNotIn("[WARN]", out1 + out2)
        # the exclude entry really hides the file from git
        status = self.git("status", "--porcelain", "--untracked-files=all").stdout
        self.assertNotIn("claudecode_jobs.yaml", status)

        # a user-authored .gitignore is left byte-identical
        gitignore.write_text("*.log\n")
        self.render()
        self.assertEqual(gitignore.read_text(), "*.log\n")

        # already tracked -> prominent warning on the next render
        self.git("add", "-f", "claudecode_jobs.yaml")
        out3, _ = self.render()
        warn = [l for l in out3.splitlines() if "[WARN]" in l]
        self.assertEqual(len(warn), 1, out3)
        self.assertIn("TRACKED by git", warn[0])
        self.assertIn("claude-job token rotate", warn[0])

