    # -- idempotence and reloads (A27) ----------------------------------------------------------
    def test_second_render_is_identical_apart_from_timestamp_and_does_not_reload(self):
        self.render()
        first = self.pkg.read_text()
        self.assertEqual(len(self.reload_posts()), 2)
        self.sup.clear()

        self.render()
        second = self.pkg.read_text()
        strip = lambda t: [l for l in t.splitlines() if "GENERATED" not in l]
        self.assertEqual(strip(first), strip(second))
        self.assertEqual(sum("GENERATED" in l for l in second.splitlines()), 1)
        self.assertEqual(self.reload_posts(), [], "identical re-render must not reload anything")
        self.assertEqual(self.pkg.stat().st_mode & 0o777, 0o600)
        self.assert_no_tmp_leftovers(self.s.ha_config)
        self.sup.clear()

        # token rotation is a material change -> reload again
        self.render(token=TOKEN2)
        third = self.pkg.read_text()
        self.assertEqual(third.count(TOKEN2), 4)
        self.assertNotIn(TOKEN, third)
        self.assertEqual(self.reload_posts(), ["/core/api/services/rest_command/reload",
                                               "/core/api/services/rest/reload"])
        self.sup.clear()

        # so is a hostname change
        self.render("--hostname", "renamed-addon", token=TOKEN2)
        self.assertEqual(len(self.reload_posts()), 2)

