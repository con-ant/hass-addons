    # -- helpers ------------------------------------------------------------------------------
    def render(self, *args, token=TOKEN, expect_rc=0, timeout=60):
        if token is not None:
            self.s.write_token(token)
        rc, out, err = run_cli([sys.executable, RENDERER, *args], self.s.env, timeout=timeout)
        self.assertEqual(rc, expect_rc, f"rc={rc}\nstdout:\n{out}\nstderr:\n{err}")
        for stream in (out, err):
            self.assertNotIn(token or TOKEN, stream, "the token must never be printed")
        for line in out.splitlines():
            self.assertTrue(line.startswith("[claude-job-package]"), line)
        return out, err

    def reload_posts(self):
        return [r["path"] for r in self.sup.find("POST", "/core/api/services/")
                if r["path"].endswith("/reload")]

    def git(self, *args, check=True):
        return subprocess.run(["git", "-C", str(self.s.ha_config), *args], env=self.s.env,
                              capture_output=True, text=True, timeout=30, check=check)

    def assert_no_tmp_leftovers(self, directory):
        leftovers = [p.name for p in Path(directory).iterdir() if ".tmp." in p.name]
        self.assertEqual(leftovers, [])

