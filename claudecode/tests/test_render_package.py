class HaLoader(yaml.SafeLoader):
    """safe_load that tolerates Home Assistant's custom tags by turning them into plain strings."""


def _tag_as_string(loader, node):
    if isinstance(node, yaml.ScalarNode):
        return f"{node.tag} {loader.construct_scalar(node)}".strip()
    if isinstance(node, yaml.SequenceNode):
        return f"{node.tag} {loader.construct_sequence(node)}"
    return f"{node.tag} {loader.construct_mapping(node)}"


for _t in ("!include", "!secret", "!input", "!include_dir_named", "!include_dir_merge_named",
           "!include_dir_list", "!include_dir_merge_list", "!env_var"):
    HaLoader.add_constructor(_t, _tag_as_string)


def ha_yaml_load(text):
    return yaml.load(text, Loader=HaLoader)


class RenderPackageTest(unittest.TestCase):
    def setUp(self):
        self.s = ScratchRoot().start()
