    def test_snippet_blocks_parse_and_reference_package_commands(self):
        doc = (ADDON / "docs" / "JOBS.md").read_text()
        start = doc.index("\n## Example dashboard")
        md = doc[start:doc.index("\n## ", start + 1)]
        blocks = re.findall(r"```yaml\n(.*?)```", md, re.S)
        self.assertEqual(len(blocks), 3)
